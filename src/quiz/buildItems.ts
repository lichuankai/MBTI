import type { QuizDim, QuizItem } from "./types";

type Stem = readonly [prompt: string, aText: string, bText: string];

function itemsForDim(
  dim: QuizDim,
  prefix: string,
  aLetter: QuizItem["aLetter"],
  bLetter: QuizItem["bLetter"],
  stems: readonly Stem[],
): QuizItem[] {
  return stems.map(([prompt, aText, bText], i) => ({
    id: `${prefix}${i + 1}`,
    dim,
    prompt,
    aLetter,
    bLetter,
    aText,
    bText,
  }));
}

